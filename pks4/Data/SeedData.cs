                VisitCost = null
            })
        };

        var existingAttractions = await db.Attractions.ToListAsync();

        foreach (var (cityName, desired) in desiredAttractions)
        {
            if (!cityIdByName.TryGetValue(cityName, out var cityId))
                continue;

            var current = existingAttractions.FirstOrDefault(a => a.CityId == cityId && a.Name == desired.Name);
            if (current is null)
            {
                desired.CityId = cityId;
                db.Attractions.Add(desired);
                continue;
            }

            current.ShortDescription = desired.ShortDescription;
            current.History = desired.History;
            current.PhotoPath = desired.PhotoPath;
            current.OpeningHours = desired.OpeningHours;
            current.VisitCost = desired.VisitCost;
        }

        await db.SaveChangesAsync();
    }
